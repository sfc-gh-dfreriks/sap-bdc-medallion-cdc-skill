/* ============================================================================
   10  Database, schemas and the capture control plane
   ----------------------------------------------------------------------------
   Generated by sap-bdc-medallion-cdc from config.yaml.
   Source : CUSTOMER_V1."customer"  (STANDARD track)
   Target : SAP_CUSTOMER_360

   Idempotent. Holds no data of its own beyond capture state. Run it first.

   Why a control plane at all: the objects in a catalog-linked database are
   Iceberg tables on an external catalog, so streams, CHANGES() and change
   tracking are all refused by the platform. What remains is a replication
   watermark SAP already writes, plus dynamic tables. Neither records what has
   already been seen, so this schema does.

   The registry stores column names and poll expressions as DATA rather than
   code. On the standard track two connector columns carry a 32-hex flow hash
   in their name (load_type_<hash>, run_id_<hash>); the hash changes when the
   product is re-published, so SQL that spells it inline breaks silently.
   ========================================================================== */

