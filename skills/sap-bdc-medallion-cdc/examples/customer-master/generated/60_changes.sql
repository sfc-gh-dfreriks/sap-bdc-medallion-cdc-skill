/* ============================================================================
   60  Changes — an I/U/D change log keyed on the declared primary key
   ----------------------------------------------------------------------------
   Generated by sap-bdc-medallion-cdc from config.yaml.
   Emitted because cdc_log is set for: CUSTOMER, CUSTOMERSALESAREATAX.

   Streams are refused on the share itself, but a standard stream on a Silver
   dynamic table is allowed. What it delivers is not an SAP change feed: an
   incremental refresh rewrites a changed row as a DELETE plus an INSERT, and
   a re-delivered, unchanged row the same way. METADATA$ISUPDATE is always
   FALSE on this path, so it is never read. Instead SP_DRAIN_CHANGES pairs the
   DELETE and INSERT rows on the primary key and compares a hash of the
   business columns:
     DELETE + INSERT, hashes differ  -> U   (before and after image kept)
     INSERT only                     -> I
     DELETE only                     -> D
     DELETE + INSERT, hashes equal   -> dropped (re-delivery, not a change)
   Pairing is only correct on the true grain, which is why the key is SAP's
   declared primary key, verified by verify_grain.py.

   Lineage columns (CDC_*) are left out of the hash: they
   move on every re-delivery.

   Re-running 30_silver (CREATE OR REPLACE DYNAMIC TABLE) invalidates these
   streams: they still exist but can no longer be read, so IF NOT EXISTS would
   skip them. Re-run this file afterwards; each stream is probed with a
   zero-row read (which does not move the offset) and recreated only if that
   read fails, so a healthy stream's offset is never silently reset.

   Scheduling is left to you: no task is created. To drain on a schedule,
   create a task that CALLs CHANGES.SP_DRAIN_CHANGES(), create it SUSPENDED,
   and drain at least as often as the stream retention period.
   ========================================================================== */

USE DATABASE SAP_CUSTOMER_360;

CREATE SCHEMA IF NOT EXISTS SAP_CUSTOMER_360.CHANGES
  COMMENT = 'Streams on Silver and the derived I/U/D change log.';

CREATE TABLE IF NOT EXISTS CHANGES.CHANGE_LOG (
  LOGGED_AT        TIMESTAMP_NTZ,
  DRAIN_ID         VARCHAR,
  OBJECT_NAME      VARCHAR,
  CHANGE_TYPE      VARCHAR(1),     -- I | U | D
  KEY_VALUES       VARIANT,        -- {"<key column>": value, ...} on the declared key
  ROW_HASH_BEFORE  NUMBER,
  ROW_HASH_AFTER   NUMBER,
  BEFORE_IMAGE     VARIANT,        -- business columns; NULL for I
  AFTER_IMAGE      VARIANT,        -- business columns; NULL for D
  CDC_TIMESTAMP_TEXT VARCHAR       -- watermark of the after image (before image for D)
)
  COMMENT = 'Insert / update / delete events derived from Silver streams on the declared primary key.';

/* --- CUSTOMER: key Customer (declared) --- */
EXECUTE IMMEDIATE $$
BEGIN
  SELECT 1 FROM CHANGES.STR_CUSTOMER LIMIT 0;   -- fails if missing, stale or its DT was replaced
  RETURN 'STR_CUSTOMER healthy, kept';
EXCEPTION
  WHEN OTHER THEN
    CREATE OR REPLACE STREAM CHANGES.STR_CUSTOMER
      ON DYNAMIC TABLE SILVER.DT_CUSTOMER
      COMMENT = 'Standard stream on SILVER.DT_CUSTOMER; drained only by CHANGES.SP_DRAIN_CHANGES.';
    RETURN 'STR_CUSTOMER (re)created';
END;
$$;

/* --- CUSTOMERSALESAREATAX: key Customer, SalesOrganization, DistributionChannel, Division, DepartureCountry, CustomerTaxCategory (declared) --- */
EXECUTE IMMEDIATE $$
BEGIN
  SELECT 1 FROM CHANGES.STR_CUSTOMERSALESAREATAX LIMIT 0;   -- fails if missing, stale or its DT was replaced
  RETURN 'STR_CUSTOMERSALESAREATAX healthy, kept';
EXCEPTION
  WHEN OTHER THEN
    CREATE OR REPLACE STREAM CHANGES.STR_CUSTOMERSALESAREATAX
      ON DYNAMIC TABLE SILVER.DT_CUSTOMERSALESAREATAX
      COMMENT = 'Standard stream on SILVER.DT_CUSTOMERSALESAREATAX; drained only by CHANGES.SP_DRAIN_CHANGES.';
    RETURN 'STR_CUSTOMERSALESAREATAX (re)created';
END;
$$;


/* ---------------------------------------------------------------------------
   Drain. The stream offsets advance only when the transaction that reads them
   commits, and the change log is written in that same transaction: either
   both happen or neither does.
   --------------------------------------------------------------------------- */
CREATE OR REPLACE PROCEDURE CHANGES.SP_DRAIN_CHANGES()
  RETURNS VARCHAR
  LANGUAGE SQL
  COMMENT = 'Drain the Silver streams into CHANGES.CHANGE_LOG as I/U/D events paired on the declared primary key.'
AS
$$
DECLARE
  v_drain  VARCHAR DEFAULT UUID_STRING();
  v_logged TIMESTAMP_NTZ DEFAULT SYSDATE();
  n_rows   NUMBER DEFAULT 0;
BEGIN
  /* DDL commits implicitly, so the staging table is created before the transaction. */
  CREATE TEMPORARY TABLE IF NOT EXISTS CHANGES.TMP_DRAIN (
    OBJECT_NAME        VARCHAR,
    CHG_ACTION         VARCHAR,
    KEY_TEXT           VARCHAR,
    KEY_VALUES         VARIANT,
    ROW_HASH           NUMBER,
    ROW_IMAGE          VARIANT,
    CDC_TIMESTAMP_TEXT VARCHAR
  );

  BEGIN TRANSACTION;
  DELETE FROM CHANGES.TMP_DRAIN;

  INSERT INTO CHANGES.TMP_DRAIN
  SELECT 'CUSTOMER', METADATA$ACTION,
         TO_JSON(OBJECT_CONSTRUCT_KEEP_NULL('Customer', "Customer")),
         OBJECT_CONSTRUCT_KEEP_NULL('Customer', "Customer"),
         HASH(img), img, CDC_TIMESTAMP_TEXT
  FROM (SELECT s.*,
               OBJECT_DELETE(OBJECT_CONSTRUCT_KEEP_NULL(s.*),
                             'METADATA$ACTION', 'METADATA$ISUPDATE', 'METADATA$ROW_ID',
                             'CDC_OPERATION', 'CDC_LOAD_TYPE', 'CDC_RUN_ID',
                             'CDC_TIMESTAMP_TEXT', 'CDC_TIMESTAMP_UTC') AS img
        FROM CHANGES.STR_CUSTOMER s);

  INSERT INTO CHANGES.TMP_DRAIN
  SELECT 'CUSTOMERSALESAREATAX', METADATA$ACTION,
         TO_JSON(OBJECT_CONSTRUCT_KEEP_NULL('Customer', "Customer", 'SalesOrganization', "SalesOrganization", 'DistributionChannel', "DistributionChannel", 'Division', "Division", 'DepartureCountry', "DepartureCountry", 'CustomerTaxCategory', "CustomerTaxCategory")),
         OBJECT_CONSTRUCT_KEEP_NULL('Customer', "Customer", 'SalesOrganization', "SalesOrganization", 'DistributionChannel', "DistributionChannel", 'Division', "Division", 'DepartureCountry', "DepartureCountry", 'CustomerTaxCategory', "CustomerTaxCategory"),
         HASH(img), img, CDC_TIMESTAMP_TEXT
  FROM (SELECT s.*,
               OBJECT_DELETE(OBJECT_CONSTRUCT_KEEP_NULL(s.*),
                             'METADATA$ACTION', 'METADATA$ISUPDATE', 'METADATA$ROW_ID',
                             'CDC_OPERATION', 'CDC_LOAD_TYPE', 'CDC_RUN_ID',
                             'CDC_TIMESTAMP_TEXT', 'CDC_TIMESTAMP_UTC') AS img
        FROM CHANGES.STR_CUSTOMERSALESAREATAX s);

  INSERT INTO CHANGES.CHANGE_LOG
    (LOGGED_AT, DRAIN_ID, OBJECT_NAME, CHANGE_TYPE, KEY_VALUES,
     ROW_HASH_BEFORE, ROW_HASH_AFTER, BEFORE_IMAGE, AFTER_IMAGE, CDC_TIMESTAMP_TEXT)
  WITH d AS (SELECT * FROM CHANGES.TMP_DRAIN WHERE CHG_ACTION = 'DELETE'),
       i AS (SELECT * FROM CHANGES.TMP_DRAIN WHERE CHG_ACTION = 'INSERT')
  SELECT :v_logged, :v_drain,
         COALESCE(i.OBJECT_NAME, d.OBJECT_NAME),
         CASE WHEN d.KEY_TEXT IS NULL THEN 'I'
              WHEN i.KEY_TEXT IS NULL THEN 'D'
              ELSE 'U' END,
         COALESCE(i.KEY_VALUES, d.KEY_VALUES),
         d.ROW_HASH, i.ROW_HASH, d.ROW_IMAGE, i.ROW_IMAGE,
         COALESCE(i.CDC_TIMESTAMP_TEXT, d.CDC_TIMESTAMP_TEXT)
  FROM d FULL OUTER JOIN i
    ON i.OBJECT_NAME = d.OBJECT_NAME AND i.KEY_TEXT = d.KEY_TEXT
  /* identical hash on both sides = re-delivery of an unchanged row */
  WHERE NOT (d.KEY_TEXT IS NOT NULL AND i.KEY_TEXT IS NOT NULL AND d.ROW_HASH = i.ROW_HASH)
  ORDER BY 3, 4;

  COMMIT;

  n_rows := (SELECT COUNT(*) FROM CHANGES.CHANGE_LOG WHERE DRAIN_ID = :v_drain);
  RETURN 'Drained ' || :n_rows || ' change(s) from 2 stream(s), drain ' || :v_drain;
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;

/* Event counts per object and drain, newest first. */
CREATE OR REPLACE VIEW CHANGES.VW_CHANGE_SUMMARY
  COMMENT = 'I/U/D counts per object per drain.'
AS
SELECT DRAIN_ID, MIN(LOGGED_AT) AS LOGGED_AT, OBJECT_NAME,
       COUNT_IF(CHANGE_TYPE = 'I') AS INSERTS,
       COUNT_IF(CHANGE_TYPE = 'U') AS UPDATES,
       COUNT_IF(CHANGE_TYPE = 'D') AS DELETES
FROM   CHANGES.CHANGE_LOG
GROUP  BY DRAIN_ID, OBJECT_NAME;
