/* ============================================================================
   20  Bronze — pass-through views onto the share
   ----------------------------------------------------------------------------
   Generated by sap-bdc-medallion-cdc from config.yaml.

   There is no Bronze TABLE, and that is the point. SAP has already landed the
   data as Iceberg and shared it zero-copy; copying it would pay twice for one
   dataset, add a hop of latency — and is actively unsafe: on a reference
   tenant the connector metadata columns were clean inside every live
   catalog-linked database and corrupted on every local copy made from one.
   So capture points at CUSTOMER_V1 itself, always.

   The views are a naming contract:
     - the share's identifiers are mixed/lower case, so quoting happens once here
     - load_type_<hash> / run_id_<hash> become LOAD_TYPE / RUN_ID, so a
       re-publish (new hash) is a re-render of this file, not an edit everywhere
     - CDC_TIMESTAMP_UTC is exposed parsed, for display only. "__TIMESTAMP" stays
       raw TEXT because comparisons must stay in text: MAX() over the raw column
       is answered from Iceberg manifest statistics; MAX() over a parsed
       expression reads the object. It arrives with a COMMA decimal separator,
       so it is REPLACEd before parsing — an unguarded cast returns NULL silently.

   Schema evolution: SELECT * fixes the column list when the view is created.
   If SAP adds columns to the product, re-run this file.
   ========================================================================== */

