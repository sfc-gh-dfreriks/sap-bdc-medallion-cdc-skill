/* ============================================================================
   30  Silver — typed, de-duplicated, incrementally refreshed
   ----------------------------------------------------------------------------
   Generated by sap-bdc-medallion-cdc from config.yaml.

   One dynamic table per populated object (EMPTY objects stay as Bronze views:
   a dynamic table over an empty source is a schedule that costs credits to
   confirm nothing is there). Silver guarantees the grain, exposes change
   lineage under stable names, and adds deterministic quality flags. Business
   renaming happens in Gold.

   Four rules carry the weight. None of them errors when broken.
     1. REFRESH_MODE = INCREMENTAL is stated, never AUTO. AUTO silently falls
        back to FULL, and one FULL object forces everything downstream to FULL.
     2. No SYSDATE() / CURRENT_TIMESTAMP() / CURRENT_DATE(). One
        non-deterministic expression blocks incremental refresh outright.
     3. De-duplicate on the VERIFIED grain. Nullable key parts are COALESCEd so
        a NULL does not form its own partition.
     4. ORDER BY the raw watermark, never a parsed expression.

   Flags: check the column type first. SAP indicator fields arrive as TEXT on
   some objects and BOOLEAN on others — even within one table — and
   COALESCE(<boolean>, '') fails at the first refresh, not at CREATE.
   ========================================================================== */

