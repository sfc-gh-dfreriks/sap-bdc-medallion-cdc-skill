/* --- CUSTOMER. Grain: Customer (declared). Verified 3,450 rows / 3,450 keys. --- */
CREATE OR REPLACE DYNAMIC TABLE SILVER.DT_CUSTOMER
  TARGET_LAG   = '24 hours'
  WAREHOUSE    = COMPUTE_WH
  REFRESH_MODE = INCREMENTAL
  COMMENT      = 'Customer master, de-duplicated on Customer. Key source: declared primary key constraint on the share (RELY, verified). Refresh driven by CAPTURE_CONTROL.SP_CAPTURE_CYCLE; the lag is a backstop.'
AS
SELECT
    * EXCLUDE ("__OPERATION_TYPE", "__TIMESTAMP", LOAD_TYPE, RUN_ID, CDC_TIMESTAMP_UTC),
    "__OPERATION_TYPE"  AS CDC_OPERATION,
    LOAD_TYPE           AS CDC_LOAD_TYPE,
    RUN_ID              AS CDC_RUN_ID,
    "__TIMESTAMP"       AS CDC_TIMESTAMP_TEXT,
    CDC_TIMESTAMP_UTC   AS CDC_TIMESTAMP_UTC,
    COALESCE("DeletionIndicator", FALSE) AS IS_FLAGGED_DELETED,
    IFF(COALESCE("DeliveryIsBlocked", '') <> '' OR COALESCE("BillingIsBlockedForCustomer", '') <> '' OR COALESCE("OrderIsBlockedForCustomer", '') <> '' OR COALESCE("PaymentIsBlockedForCustomer", FALSE) OR COALESCE("PostingIsBlocked", FALSE), TRUE, FALSE) AS IS_BLOCKED_ANY,
    IFF(COALESCE("CustomerName", '') = '', TRUE, FALSE) AS DQ_NAME_MISSING,
    IFF(COALESCE("Country", '') = '', TRUE, FALSE) AS DQ_COUNTRY_MISSING
FROM BRONZE.V_CUSTOMER
QUALIFY ROW_NUMBER() OVER (PARTITION BY "Customer"
                           ORDER BY "__TIMESTAMP" DESC) = 1;

